@dataclass
class Block:
    """f' = -Ks(z) f + (m(z) + w) g ;  g' = Ks(z) g + (m(z) - w) f ;  f(0) cos th + g(0) sin th = 0.

    Ks(z) = Kinf * (1 - e^{-12Hz})^{1/12} (Kinf SIGNED: + for irrep w3 = -i, - for w3 = +i);
    set Kconst=True for a constant K (validation).  m: constant m_inf, or a tabulated profile
    (mz_grid, mz_vals) with m(z) = m_inf for z >= z_a.
    """
    Kinf: float
    m: float = 1.0                  # m_inf (bulk value)
    theta: float = -math.pi / 4     # MIT+ by default
    H: float = 1.0
    za: float | None = None         # start of the asymptotic (constant-coefficient) region
    Kconst: bool = False
    mz_grid: np.ndarray | None = None
    mz_vals: np.ndarray | None = None

    def __post_init__(self):
        if self.za is None:
            # K(z)/K_inf - 1 ~ e^{-12Hz}/12 < 2e-17 for z >= 3/H
            self.za = 3.0 / self.H if self.mz_grid is None else float(self.mz_grid[-1])
        self.R = math.hypot(self.m, self.Kinf)
        self.alpha = math.atan2(self.Kinf, self.m)

    # -- coefficients ------------------------------------------------------------------------
    def K(self, z):
        if self.Kconst:
            return self.Kinf + 0.0 * np.asarray(z, dtype=float)
        return K_profile(z, self.Kinf, self.H)

    def mz(self, z):
        if self.mz_grid is None:
            return self.m + 0.0 * np.asarray(z, dtype=float)
        return np.interp(z, self.mz_grid, self.mz_vals, right=self.m)

    def Kscalar(self, z):
        if self.Kconst:
            return self.Kinf
        return self.Kinf * (-math.expm1(-12.0 * self.H * z)) ** (1.0 / 12.0)

    def mscalar(self, z):
        if self.mz_grid is None:
            return self.m
        return float(np.interp(z, self.mz_grid, self.mz_vals, right=self.m))

    # -- angles --------------------------------------------------------------------------------
    @property
    def p_wall(self):
        return self.theta + math.pi / 2          # direction (-sin th, cos th)

    def p_decay(self, w):
        """Angle of the exactly decaying solution in the constant region (w in [-R, R])."""
        c = max(-1.0, min(1.0, w / self.R))
        return 0.5 * (self.alpha - math.acos(c))

    def kappa(self, w):
        return math.sqrt(max(self.R * self.R - w * w, 0.0))

    def allowed_end(self, w):
        """End of the classically allowed region adjacent to the wall (w^2 > m(z)^2 + K(z)^2), or 0."""
        if self.mz_grid is None:
            m2 = self.m ** 2
            if w * w <= m2:
                return 0.0
            if self.Kconst:
                return self.za if w * w > m2 + self.Kinf ** 2 else 0.0
            x = (w * w - m2) / (self.Kinf ** 2) if self.Kinf != 0 else np.inf
            if x >= 1.0:
                return self.za
            # K(z)^2 = K^2 (1-e^{-12Hz})^{1/6} = w^2 - m^2
            return min(self.za, -math.log1p(-x ** 6) / (12.0 * self.H))
        zg = self.mz_grid
        ok = w * w > self.mz(zg) ** 2 + self.K(zg) ** 2
        if not ok[0] and not ok[1]:
            return 0.0
        idx = np.argmin(ok) if not ok.all() else len(zg) - 1
        return float(zg[idx])

    def default_zm(self, w):
        zt = self.allowed_end(w)
        return 0.5 * zt if zt > 0 else 0.0


