def wavefunction(blk: Block, w, z, rtol=1e-12, zm=None):
    """(f, g) on the array z for a level w, normalized Int_0^inf (f^2 + g^2) dz = 1.

    Built from the left and right Pruefer solutions (p, ln r), matched at zm (vectors parallel at a
    level, up to the sign (-1)^j); exact exponential tail beyond z_a.  Returns f, g, info."""
    z = np.asarray(z, float)
    if zm is None:
        zm = blk.default_zm(w)
    pL, pR, left, right, zm = prufer_ivp(blk, w, zm, rtol, rtol, dense=True)
    jj = int(round((pL - pR) / math.pi))
    sign = -1.0 if (jj % 2) else 1.0
    lnrL = left.sol(zm)[1] if left is not None else 0.0
    shift = lnrL - right.sol(zm)[1]
    kap = blk.kappa(w)
    pza, lza = right.sol(blk.za)

    def evaluate(zs):
        p = np.empty_like(zs)
        lr = np.empty_like(zs)
        sg = np.ones_like(zs)
        iL = zs <= zm if left is not None else np.zeros_like(zs, bool)
        iR = (~iL) & (zs <= blk.za)
        iT = zs > blk.za
        if iL.any():
            v = left.sol(zs[iL]); p[iL], lr[iL] = v[0], v[1]
        if iR.any():
            v = right.sol(zs[iR]); p[iR], lr[iR] = v[0], v[1] + shift; sg[iR] = sign
        if iT.any():
            p[iT] = pza; lr[iT] = lza + shift - kap * (zs[iT] - blk.za); sg[iT] = sign
        r = np.exp(lr)
        return sg * r * np.cos(p), sg * r * np.sin(p)

    f, g = evaluate(z)
    zz = np.unique(np.concatenate((make_grid(0.0, blk.za, min(0.001, 0.1 / (abs(w) + blk.R + 1))), [zm])))
    fz, gz = evaluate(zz)
    norm2 = simpson(fz * fz + gz * gz, x=zz)
    tail = (fz[-1] ** 2 + gz[-1] ** 2) / (2 * kap) if kap > 0 else np.inf
    norm2 += tail
    c = 1.0 / math.sqrt(norm2)
    return f * c, g * c, dict(norm2_raw=norm2, zm=zm, j=jj, tail_fraction=tail / norm2,
                              left_right_residual=(pL - pR) - jj * math.pi)


