def branch_counts(Kinf, m, theta, H=1.0):
    """(#positive levels, #negative levels) of the block ODE with signed Kinf (reference integrator, z_m = 0).

    Delta is monotone decreasing: #(0 < w < R) = #{j: Delta(R) < j pi < Delta(0)}, etc."""
    blk = Block(Kinf=Kinf, m=m, theta=theta, H=H)
    Dp = delta_ivp(blk, blk.R, 0.0)
    D0 = delta_ivp(blk, 0.0, 0.0)
    Dm = delta_ivp(blk, -blk.R, 0.0)
    npos = max(0, (math.ceil(D0 / math.pi) - 1) - (math.floor(Dp / math.pi) + 1) + 1)
    nneg = max(0, (math.ceil(Dm / math.pi) - 1) - (math.floor(D0 / math.pi) + 1) + 1)
    return npos, nneg


def positive16(Kinf, m, eps, H=1.0):
    """Number of positive levels of the 16-component MIT problem (per 4-fold unit) = #A(K) (both signs),
    split by irrep: (total, n(-i) = positive levels of A, n(+i) = negative levels of A)."""
    npos, nneg = branch_counts(Kinf, m, theta_MIT(eps), H)
    return npos + nneg, npos, nneg


def threshold_scan(m, eps=+1, H=1.0, nmax=2, Kmax=None, rel=1e-9):
    """K_inf where the 1st, 2nd, ... positive level of the 16-component MIT problem appears
    (bisection on the exact count); also in which irrep each new level appears."""
    Kmax = Kmax or max(80.0, 80.0 * m)
    Ks = np.unique(np.geomspace(0.02 * max(m, 0.25), Kmax, 240))
    prev = positive16(Ks[0], m, eps, H)
    out = []
    for i in range(1, len(Ks)):
        K = Ks[i]
        cur = positive16(K, m, eps, H)
        if cur[0] != prev[0]:
            lo, hi, plo, phi = Ks[i - 1], K, prev, cur
            while hi - lo > rel * hi:
                mid = 0.5 * (lo + hi)
                pm = positive16(mid, m, eps, H)
                if pm[0] == plo[0]:
                    lo, plo = mid, pm
                else:
                    hi, phi = mid, pm
            irrep = "-i" if phi[1] > plo[1] else "+i"
            out.append(dict(n_before=plo[0], n_after=phi[0], K=0.5 * (lo + hi), irrep=irrep))
            if phi[0] >= nmax:
                break
        prev = cur
    return out


