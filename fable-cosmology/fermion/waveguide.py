_G1 = 0.5 - math.sqrt(3.0) / 6.0
_G2 = 0.5 + math.sqrt(3.0) / 6.0


def make_grid(z0, z1, hmax, wall_refine=True, ratio=1.02, zgeo=0.05, H=1.0):
    """Nonuniform grid on [z0, z1].  With a wall at z0 = 0: geometric spacing (ratio) from 1e-14 up to
    zgeo/H, because K(z) ~ z^{1/12} and Sin(z) ~ z^{1/2} are not smooth at the wall; then steps <= hmax."""
    if z1 <= z0:
        return np.array([z0])
    pts = []
    zstart = z0
    if wall_refine and z0 == 0.0:
        zg = min(zgeo / H, 0.5 * z1)
        ng = int(math.ceil(math.log(zg / 1e-14) / math.log(ratio))) + 1
        geo = np.geomspace(1e-14, zg, ng)
        # cap the geometric steps by hmax as well
        geo = geo[np.concatenate(([True], np.diff(geo) > 0))]
        pts.append(np.concatenate(([0.0], geo)))
        zstart = zg
    n = max(2, int(math.ceil((z1 - zstart) / hmax)) + 1)
    pts.append(np.linspace(zstart, z1, n))
    g = np.unique(np.concatenate(pts))
    # enforce h <= hmax inside the geometric part too
    d = np.diff(g)
    if np.any(d > hmax * (1 + 1e-12)):
        extra = [np.linspace(g[i], g[i + 1], int(math.ceil(d[i] / hmax)) + 1)[1:-1] for i in np.where(d > hmax)[0]]
        g = np.unique(np.concatenate([g] + extra))
    return g


class MagnusPath:
    """Precomputed step data of y' = A(z) y on a grid, A = -Ks(z) sz + m(z) sx + w J2 (J2 = i sy).

    Omega_n = (h/2)(A1 + A2) + (sqrt3 h^2/12)[A2, A1] (Gauss points) = al sz + be sx + ga J2,
    Omega^2 = (al^2 + be^2 - ga^2) 1, exp(Omega) = C 1 + S Omega.
    """

    def __init__(self, blk: Block, grid, Kscale=None):
        self.blk = blk
        self.z = np.asarray(grid, float)
        z0, z1 = self.z[:-1], self.z[1:]
        self.h = z1 - z0
        za = z0 + _G1 * self.h
        zb = z0 + _G2 * self.h
        self.a1 = -blk.K(za)
        self.a2 = -blk.K(zb)
        self.b1 = blk.mz(za)
        self.b2 = blk.mz(zb)

    def steps(self, w, backward=False):
        """Return arrays (C, S, al, be, ga) of shape (nsteps, nw) for the w array."""
        w = np.atleast_1d(np.asarray(w, float))
        h = self.h[:, None]
        a1, a2 = self.a1[:, None], self.a2[:, None]
        b1, b2 = self.b1[:, None], self.b2[:, None]
        c1 = c2 = w[None, :]
        sq = math.sqrt(3.0) / 12.0 * h * h
        al = 0.5 * h * (a1 + a2) - 2.0 * sq * (b2 * c1 - c2 * b1)
        be = 0.5 * h * (b1 + b2) - 2.0 * sq * (c2 * a1 - a2 * c1)
        ga = 0.5 * h * (c1 + c2) + 2.0 * sq * (a2 * b1 - b2 * a1)
        if backward:
            al, be, ga = -al, -be, -ga
        lam2 = al * al + be * be - ga * ga
        lam = np.sqrt(np.abs(lam2))
        small = lam < 1e-6
        with np.errstate(over="ignore", invalid="ignore", divide="ignore"):
            C = np.where(lam2 >= 0, np.cosh(lam), np.cos(lam))
            S = np.where(lam2 >= 0, np.sinh(lam) / np.where(small, 1.0, lam), np.sin(lam) / np.where(small, 1.0, lam))
        C = np.where(small, 1.0 + 0.5 * lam2, C)
        S = np.where(small, 1.0 + lam2 / 6.0, S)
        return C, S, al, be, ga


def magnus_propagate(path: MagnusPath, w, y0, p0, backward=False, store=False):
    """Propagate unit vectors y0 (2, nw) along the path; track the continuous Pruefer angle and ln r.

    forward: from path.z[0] to path.z[-1];  backward: from path.z[-1] to path.z[0].
    Returns p_end, lnr_end (and per-node arrays when store=True, ordered like path.z).
    """
    C, S, al, be, ga = path.steps(w, backward)
    n = C.shape[0]
    f = np.array(y0[0], float, copy=True)
    g = np.array(y0[1], float, copy=True)
    p = np.array(p0, float, copy=True) * np.ones_like(f)
    lnr = np.zeros_like(f)
    order = range(n - 1, -1, -1) if backward else range(n)
    if store:
        P = np.empty((n + 1, f.size))
        L = np.empty((n + 1, f.size))
        idx0 = n if backward else 0
        P[idx0], L[idx0] = p, lnr
    for i in order:
        Ci, Si, a, b, c = C[i], S[i], al[i], be[i], ga[i]
        # exp(Omega) = C + S [[a, b + c], [b - c, -a]]
        fn = (Ci + Si * a) * f + Si * (b + c) * g
        gn = Si * (b - c) * f + (Ci - Si * a) * g
        dp = np.arctan2(f * gn - g * fn, f * fn + g * gn)
        nr = np.hypot(fn, gn)
        f, g = fn / nr, gn / nr
        p = p + dp
        lnr = lnr + np.log(nr)
        if store:
            j = i if backward else i + 1
            P[j], L[j] = p, lnr
    if store:
        return p, lnr, P, L
    return p, lnr


def delta_magnus(blk: Block, ws, zm, hmax=None):
    """Delta(w) for an array of w at a common matching point zm (Magnus)."""
    ws = np.atleast_1d(np.asarray(ws, float))
    if hmax is None:
        hmax = min(0.004 / blk.H, 0.25 / (np.max(np.abs(ws)) + blk.R + 1.0))
    nw = ws.size
    if zm > 0:
        gl = make_grid(0.0, zm, hmax)
        pl = MagnusPath(blk, gl)
        th = blk.theta
        y0 = np.vstack([np.full(nw, -math.sin(th)), np.full(nw, math.cos(th))])
        pL, _ = magnus_propagate(pl, ws, y0, blk.p_wall)
    else:
        pL = np.full(nw, blk.p_wall)
    gr = make_grid(zm, blk.za, hmax, wall_refine=(zm == 0.0))
    pr = MagnusPath(blk, gr)
    pd = np.array([blk.p_decay(w) for w in ws])
    y0 = np.vstack([np.cos(pd), np.sin(pd)])
    pR, _ = magnus_propagate(pr, ws, y0, pd, backward=True)
    return pL - pR


