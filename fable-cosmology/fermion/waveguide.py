def dft_run(scenario="all", quick=False):
    """The Kohn-Sham runs reported in waveguide_REPORT.txt.  Parameters (H = 1, a4 = 0, V_hid = 1/H^3):
       functional W = m0 sigma + (lam/2) sigma^2, m0 = 1, lam = -0.01 (attractive; unique homogeneous gap root)."""
    m0, lam = 1.0, -0.01
    out = {}
    if scenario in ("all", "free"):
        print("\n[DFT-a] author's mass term W = m0 sigma (lam = 0): the theory is FREE (bilinear action); the single-"
              "\nparticle levels above are exact, no self-consistency.  Lowest positive energies of the whole spectrum:")
        for K in (0.0, 1.0, 3.0, 6.0, 6.7, 7.0, 10.0):
            lv, _ = find_levels(Block(Kinf=max(K, 1e-9), m=m0, theta=-math.pi / 4))
            lv2, _ = find_levels(Block(Kinf=-max(K, 1e-9), m=m0, theta=-math.pi / 4))
            pos = sorted([L.w for L in lv if L.w > 0] + [L.w for L in lv2 if L.w > 0])
            print(f"   same-sign wall, K = {K:5.2f}: bound positive levels {[round(w, 6) for w in pos]}; continuum from {math.hypot(m0, K):.6f}")
    if scenario in ("all", "same"):
        Ns = 100.0
        print(f"\n[DFT-b] same-sign MIT wall, wall-bound sector: m0 = {m0}, lam = {lam}, N_s = {Ns} (per unit coordinate 3-volume, V_hid = 1)")
        kg = np.linspace(0.0, 20.0, 41)
        gs = ks_solve(Ns, m0=m0, lam=lam, eps=+1, kgrid=kg, tol=1e-9)
        out["same_gs"] = gs
        print(f"   ground state: converged={gs.converged} in {gs.iterations} it.; E/A = {gs.E_per_A:.10f}; sum omega = {gs.sum_omega:.10f};"
              f" E_int = {gs.E_int:.10f}; mu = {gs.mu:.10f}; E/N = {gs.E_per_A / Ns:.8f}")
        for o in gs.occupations:
            print(f"      {o['band']}: k in [{o['k_lo']:.8f}, {o['kF']:.8f}], N = {o['N']:.8f} ({o['N'] / Ns:.4f} of N_s), bottom {o['w_bottom']:.8f}")
        i = int(np.argmax(gs.sigma))
        print(f"      sigma_max = {gs.sigma[i]:.8f} at z = {gs.z[i]:.5f}; m_min = {gs.m.min():.8f} at z = {gs.z[np.argmin(gs.m)]:.5f}; m(Z) - m0 = {gs.m[-1] - m0:.2e}")
        print(f"      stability: mu - m0 = {gs.mu - m0:.6f} > 0: the bulk continuum (omega >= sqrt(m0^2 + k^2) >= m0) lies BELOW mu;"
              "\n      this is the lowest state of the wall-bound sector (every orbital a true bound state at its k), NOT the global ground state.")
