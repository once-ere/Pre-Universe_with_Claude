def _rhs(blk: Block, w):
    Kc, Kinf, H, m = blk.Kconst, blk.Kinf, blk.H, blk.m
    if blk.mz_grid is None:
        if Kc:
            def f(z, y):
                c2, s2 = math.cos(2 * y[0]), math.sin(2 * y[0])
                return [m * c2 + Kinf * s2 - w, m * s2 - Kinf * c2]
        else:
            def f(z, y):
                K = Kinf * (-math.expm1(-12.0 * H * z)) ** (1.0 / 12.0)
                c2, s2 = math.cos(2 * y[0]), math.sin(2 * y[0])
                return [m * c2 + K * s2 - w, m * s2 - K * c2]
    else:
        zg, mv = blk.mz_grid, blk.mz_vals

        def f(z, y):
            K = blk.Kscalar(z)
            mm = float(np.interp(z, zg, mv, right=m))
            c2, s2 = math.cos(2 * y[0]), math.sin(2 * y[0])
            return [mm * c2 + K * s2 - w, mm * s2 - K * c2]
    return f


def prufer_ivp(blk: Block, w, zm=None, rtol=1e-12, atol=1e-12, dense=False):
    """Left (from the wall) and right (from z_a, exact decaying direction) Pruefer solutions."""
    if zm is None:
        zm = blk.default_zm(w)
    f = _rhs(blk, w)
    left = right = None
    if zm > 0:
        left = solve_ivp(f, (0.0, zm), [blk.p_wall, 0.0], method="DOP853", rtol=rtol, atol=atol,
                         first_step=1e-12, dense_output=dense)
    right = solve_ivp(f, (blk.za, zm), [blk.p_decay(w), 0.0], method="DOP853", rtol=rtol, atol=atol,
                      dense_output=dense)
    pL = left.y[0, -1] if left is not None else blk.p_wall
    pR = right.y[0, -1]
    return pL, pR, left, right, zm


def delta_ivp(blk: Block, w, zm=None, rtol=1e-12, atol=1e-12):
    pL, pR, *_ = prufer_ivp(blk, w, zm, rtol, atol)
    return pL - pR


