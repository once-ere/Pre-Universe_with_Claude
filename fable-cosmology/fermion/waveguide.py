def full16_singular_values(w, Kinf, m, eps, T, H=1.0, zm=None, za=3.0, hmax=None, P=None):
    """Singular values of [Q_left | Q_right] (16x16) for the FULL 16-component problem
        Psi' = T0 (m - i K(z) T1 + i w T4) Psi,   wall  P Psi(0) = Psi(0)  (default P = eps T0, MIT),
    integrated with a 4th-order Magnus / matrix-exponential propagator on the 8-dim subspaces
    (independent of the 2x2 block reduction and of the Pruefer code).  The number of (near-)zero
    singular values is the multiplicity of w (0 if w is not a level)."""
    from scipy.linalg import expm
    I16 = np.eye(16)
    A0 = T[0] @ (m * I16 + 1j * w * T[4])
    B = -1j * (T[0] @ T[1])
    C = B @ A0 - A0 @ B
    blk = Block(Kinf=Kinf, m=m, theta=theta_MIT(eps), H=H)
    if zm is None:
        zm = blk.default_zm(w)
    if hmax is None:
        hmax = min(0.004, 0.25 / (abs(w) + math.hypot(m, Kinf) + 1.0))
    if P is None:
        P = eps * T[0]
    ev, V = np.linalg.eigh(P)
    Y0 = V[:, ev > 0].astype(complex)                   # the 8-dim wall subspace P Psi = Psi
    Minf = A0 + Kinf * B
    ev2, V2 = np.linalg.eig(Minf)
    Yinf = V2[:, np.argsort(ev2.real)[:8]]              # the 8 decaying directions (eigenvalue -kappa)
    c = math.sqrt(3.0) / 12.0

    def prop(grid, Y, backward):
        z0, z1 = grid[:-1], grid[1:]
        h = z1 - z0
        K1 = K_profile(z0 + _G1 * h, Kinf, H)
        K2 = K_profile(z0 + _G2 * h, Kinf, H)
        order = range(len(h) - 1, -1, -1) if backward else range(len(h))
        for n, i in enumerate(order):
            Om = h[i] * A0 + 0.5 * h[i] * (K1[i] + K2[i]) * B + c * h[i] ** 2 * (K2[i] - K1[i]) * C
            Y = expm(-Om if backward else Om) @ Y
            if n % 16 == 15:
                Y, _ = np.linalg.qr(Y)
        return np.linalg.qr(Y)[0]

    QL = prop(make_grid(0.0, zm, hmax), Y0, False) if zm > 0 else np.linalg.qr(Y0)[0]
    QR = prop(make_grid(zm, za, hmax, wall_refine=(zm == 0.0)), Yinf, True)
    return np.linalg.svd(np.hstack([QL, QR]), compute_uv=False), zm


def full16_level(w0, Kinf, m, eps, T, dw=1e-3, H=1.0):
    """Independent location of a level from the 16x16 system: minimize the 4th-smallest ... the smallest
    singular value of [Q_left | Q_right] over w in [w0 - dw, w0 + dw] (bounded Brent), at a fixed
    matching point.  Returns (w, multiplicity, smallest singular value)."""
    from scipy.optimize import minimize_scalar
    blk = Block(Kinf=Kinf, m=m, theta=theta_MIT(eps), H=H)
    zm = blk.default_zm(w0)
    fun = lambda w: math.log(full16_singular_values(w, Kinf, m, eps, T, H=H, zm=zm)[0][-1])
    r = minimize_scalar(fun, bounds=(w0 - dw, w0 + dw), method="bounded", options=dict(xatol=1e-12, maxiter=200))
    sv, _ = full16_singular_values(r.x, Kinf, m, eps, T, H=H, zm=zm)
    return r.x, int(np.sum(sv < 1e-6)), sv[-1]


