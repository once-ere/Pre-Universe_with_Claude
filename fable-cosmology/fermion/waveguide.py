def sin6(z, H=1.0):
    """Sin[6 H x0(z)] = Sqrt[1 - e^{-12 H z}]  (0 at the wall, -> 1 far away)."""
    return np.sqrt(-np.expm1(-12.0 * H * np.asarray(z, dtype=float)))


def s6(z, H=1.0):
    """Sin^{1/6} = (1 - e^{-12 H z})^{1/12}: K(z) = K_inf * s6(z)."""
    return (-np.expm1(-12.0 * H * np.asarray(z, dtype=float))) ** (1.0 / 12.0)


def K_profile(z, Kinf, H=1.0):
    return Kinf * s6(z, H)


def z_of_x0(x0, H=1.0):
    return -np.log(np.cos(6.0 * H * x0)) / (6.0 * H)


def x0_of_z(z, H=1.0):
    return np.arccos(np.exp(-6.0 * H * z)) / (6.0 * H)


def bulk_threshold(m, Kinf):
    """Bulk continuum edge: |w| >= Sqrt[m^2 + K_inf^2]."""
    return math.hypot(m, Kinf)


def theta_MIT(eps):
    """MIT T0 Psi = eps Psi  <=>  f = eps g  <=>  f cos th + g sin th = 0 with th = -eps pi/4."""
    return -math.pi / 4 if eps > 0 else math.pi / 4


