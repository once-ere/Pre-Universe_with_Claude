@dataclass
class Level:
    w: float
    kappa: float
    j: int
    zm: float
    delta_residual: float
    branch: int  # +1: w > 0 branch, -1: w < 0 branch

    def as_dict(self):
        return dict(w=self.w, kappa=self.kappa, j=self.j, zm=self.zm, residual=self.delta_residual)


def _delta(blk, w, zm, method, rtol):
    if method == "ivp":
        return delta_ivp(blk, w, zm, rtol=rtol, atol=rtol)
    return float(delta_magnus(blk, [w], zm)[0])


def level_count(blk: Block, zm_fixed=None, method="ivp", rtol=1e-12):
    """Exact number of levels in (-R, R) from the monotone mismatch at the two continuum edges.

    The same matching point must be used at both edges (Delta is continuous in w only at fixed zm);
    we use zm = zm_fixed or 0 (pure backward shooting)."""
    zm = 0.0 if zm_fixed is None else zm_fixed
    Dp = _delta(blk, blk.R, zm, method, rtol)
    Dm = _delta(blk, -blk.R, zm, method, rtol)
    jlo = math.floor(Dp / math.pi) + 1
    jhi = math.ceil(Dm / math.pi) - 1
    return max(0, jhi - jlo + 1), Dp, Dm, zm


def find_levels(blk: Block, n_kappa=80, kappa_min_rel=1e-10, method="ivp", scan="magnus",
                zm_mode="allowed", rtol=1e-12, xtol=1e-14, verbose=False):
    """All levels of one block problem in the gap (-R, R).

    1. count:   #levels = #{j : Delta(+R) < j pi < Delta(-R)} (reference integrator, z_m = 0);
    2. scan:    for each sign of w, the decay rate kappa runs over [0] + a LOG grid
                [kappa_min_rel R, R] and Delta(w(kappa)) is evaluated at the FIXED matching point
                z_m = 0 (pure backward shooting; Delta is continuous in w only at fixed z_m);
                every crossing of a multiple j pi between neighbouring nodes brackets one level;
    3. refine:  brentq in kappa with the reference integrator, matching at
                zm_mode = "allowed": the middle of the classically allowed region next to the wall
                (w^2 > m^2 + K(z)^2) common to the whole bracket, or 0 if there is none;
                zm_mode = float: that fixed z_m.  (At a level the integer j is independent of z_m.)
    The number of levels found is compared with the count; a mismatch is printed as a warning.
    """
    R = blk.R
    count, Dp, Dm, _ = level_count(blk, zm_fixed=0.0, method=method, rtol=rtol)
    found = []
    for sgn in (+1, -1):
        kap = np.concatenate(([0.0], np.geomspace(kappa_min_rel * R, R, n_kappa)))
        wk = sgn * np.sqrt(np.maximum(R * R - kap * kap, 0.0))
        if scan == "magnus":
            D = delta_magnus(blk, wk, 0.0)
            D[0] = _delta(blk, wk[0], 0.0, method, rtol)          # the edge value used by the count
        else:
            D = np.array([_delta(blk, w, 0.0, method, rtol) for w in wk])
        for i in range(len(kap) - 1):
            a, b = D[i], D[i + 1]
            lo, hi = min(a, b), max(a, b)
            for j in range(math.floor(lo / math.pi) + 1, math.ceil(hi / math.pi)):
                if sgn < 0 and i == len(kap) - 2 and abs(j * math.pi - D[-1]) < 1e-9:
                    continue  # w = 0 exactly: counted on the + branch
                ka, kb = kap[i], kap[i + 1]
                if isinstance(zm_mode, (int, float)):
                    zm = float(zm_mode)
                else:
                    zt = min(blk.allowed_end(sgn * math.sqrt(max(R * R - ka * ka, 0.0))),
                             blk.allowed_end(sgn * math.sqrt(max(R * R - kb * kb, 0.0))))
                    zm = 0.5 * zt if zt > 0 else 0.0
                fun = lambda k, j=j, zm=zm: _delta(blk, sgn * math.sqrt(max(R * R - k * k, 0.0)), zm, method, rtol) - j * math.pi
                fa, fb = fun(ka), fun(kb)
                if fa * fb > 0:        # scan and refiner disagree about the bracket: widen by one cell
                    ka, kb = kap[max(i - 1, 0)], kap[min(i + 2, len(kap) - 1)]
                    fa, fb = fun(ka), fun(kb)
                    if fa * fb > 0:
                        print(f"   [warn] bracket lost: Kinf={blk.Kinf} m={blk.m} th={blk.theta:.4f} j={j} kappa~{kap[i]:.3e}")
                        continue
                kr = brentq(fun, ka, kb, xtol=xtol, rtol=1e-15, maxiter=200)
                wr = sgn * math.sqrt(max(R * R - kr * kr, 0.0))
                found.append(Level(wr, kr, j, zm, fun(kr), sgn))
    found.sort(key=lambda L: L.w)
    uniq = []
    for L in found:
        if not uniq or abs(L.w - uniq[-1].w) > 1e-9 * max(1.0, R):
            uniq.append(L)
    if len(uniq) != count:
        print(f"   [warn] Kinf={blk.Kinf} m={blk.m} th={blk.theta:.4f}: found {len(uniq)} levels, count says {count}"
              f" (Delta(+R)={Dp:.6f}, Delta(-R)={Dm:.6f})")
    return uniq, count


def spectrum16(Kinf, m=1.0, theta=-math.pi / 4, H=1.0, **kw):
    """16-component spectrum at transverse momentum K_inf >= 0 for a UNIFORM wall condition th.

    Returns a list of dicts {w, irrep ('-i' or '+i'), mult (4), kappa}:  irrep -i = block ODE with +K,
    irrep +i = block ODE with -K (basis v2 = -alx v1, same th)."""
    out = []
    for s, name in ((+1, "-i"), (-1, "+i")):
        blk = Block(Kinf=s * Kinf, m=m, theta=theta, H=H)
        lv, cnt = find_levels(blk, **kw)
        for L in lv:
            out.append(dict(w=L.w, irrep=name, mult=4, kappa=L.kappa, j=L.j))
    out.sort(key=lambda d: d["w"])
    return out


