def walecka_energy(G: KSGrid, m_nodes, m0, lam, Ns, kgrid, n_gl=16):
    """Walecka functional Omega[m] = sum_occ omega[m] (common Fermi level at N_s) + Int (m-m0)^2/(2|lam|) dz/Sin
    for a GIVEN mass profile on the grid G (no self-consistency)."""
    G.set_mass(m_nodes, m0)
    bands = build_bands(G, kgrid, m0)
    Nfun = lambda mu: sum(_dos(b.kF(mu), b.k_lo) for b in bands) - Ns
    mu_lo = min(b.w[0] for b in bands) + 1e-12
    mu = brentq(Nfun, mu_lo, mu_lo + 1e3, xtol=1e-13)
    xg, wg_ = np.polynomial.legendre.leggauss(n_gl)
    sw = 0.0
    for b in bands:
        kF = b.kF(mu)
        if kF <= b.k_lo:
            continue
        kn = 0.5 * (kF - b.k_lo) * xg + 0.5 * (kF + b.k_lo)
        wn = 0.5 * (kF - b.k_lo) * wg_
        wl = G.solve_levels(b.s * kn, np.sqrt(m0 ** 2 + kn ** 2), np.full(kn.size, float(b.j)))
        sw += float(np.sum(4.0 / (2 * math.pi ** 2) * wn * kn ** 2 * wl))
    with np.errstate(divide="ignore", invalid="ignore"):
        integ = np.where(G.sin > 0, (np.asarray(m_nodes) - m0) ** 2 / G.sin, 0.0)
    return sw + float(simpson(integ, x=G.z)) / (2 * abs(lam)), mu


