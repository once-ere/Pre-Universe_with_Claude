def _refine_level(blk, w0, j, zm, rtol=1e-12, magnus_h=None):
    """Re-solve one level near w0 with Pruefer index j, at the given matching point / tolerance."""
    k0 = blk.kappa(w0)
    sg = 1 if w0 > 0 else -1
    if magnus_h is None:
        f = lambda k: delta_ivp(blk, sg * math.sqrt(max(blk.R ** 2 - k * k, 0)), zm, rtol=rtol, atol=rtol) - j * math.pi
    else:
        f = lambda k: float(delta_magnus(blk, [sg * math.sqrt(max(blk.R ** 2 - k * k, 0))], zm, hmax=magnus_h)[0]) - j * math.pi
    for widen in (1e-4, 1e-3, 1e-2):
        lo, hi = max(k0 * (1 - widen), 0.0), min(k0 * (1 + widen), blk.R)
        try:
            kr = brentq(f, lo, hi, xtol=1e-15, rtol=1e-15)
            return sg * math.sqrt(blk.R ** 2 - kr * kr)
        except ValueError:
            continue
    return float("nan")


