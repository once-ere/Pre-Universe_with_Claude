r"""
Functional (per unit COORDINATE observed 3-volume A_obs, hidden coordinate volume V_hid = 1/H^3,
a4 = 0 so that coordinate = asymptotic proper transverse volume):

    W(sigma) = m0 sigma + (lam/2) sigma^2,   lam < 0 (attractive),   m(z) = W'(sigma(z)) = m0 + lam sigma(z)

    sigma(z) = <Psibar Psi>_8(z)  (per PROPER 7-volume, Krein-weighted, J-eigenmodes, no-sea)
             = Sin(z)/(A_obs V_hid) * sum_occ (f^2 - g^2)(z)        [the transverse proper volume is q^3 p^3 A V = A V / Sin]
    sum_occ / A_obs = sum_bands 4 Int d^3k/(2pi)^3 theta(occupied)    [4 states per band per transverse k: the 2+2 blocks
                                                                       (J = +1, -1) of ONE irrep; the other irrep is a
                                                                       different band (its levels are -A(K))]
    n(z) (number density) = Sin(z) sum_occ (f^2 + g^2),    N_s = Int n dz/Sin = sum_occ 1

    E/A = sum_occ omega + Int_0^inf (W - sigma W') dz/Sin(z) = sum_occ omega + (|lam|/2) Int sigma^2 / Sin dz
          (the proper 7-volume element per unit coordinate transverse volume is dz / Sin(z)).

The Dirac sea (negative-omega levels) is not included in sigma (no-sea approximation; its vacuum
polarization is absorbed into / neglected against W).  E_xc is neglected (Hartree = mean field).

Numerics: one nonuniform z-grid [0, Z]; for a batch of (K_signed, w) pure backward Magnus shooting
from Z (exact decaying eigenvector with m_inf = m0, K(Z) = K_inf) to the wall; levels by the exact
count and vectorized bisection in log kappa; thresholds by bisection in k on Delta(R(k), k) = j pi;
bands omega_b(k) interpolated (PCHIP) on a k-grid; Fermi level by brentq on N(mu) = N_s; sigma(z)
by Gauss-Legendre in k over each occupied interval with the orbitals computed AT the nodes.
"""

from scipy.interpolate import PchipInterpolator


class KSGrid:
    """Fixed z-grid with a mass profile m(z) (m = m_inf beyond Z) for batched Magnus shooting."""

    def __init__(self, Z=30.0, h_near=0.003, z_near=4.0, h_far=0.02, H=1.0, theta=-math.pi / 4):
        g1 = make_grid(0.0, z_near, h_near, H=H)
        n2 = max(2, int(math.ceil((Z - z_near) / h_far)) + 1)
        self.z = np.unique(np.concatenate((g1, np.linspace(z_near, Z, n2))))
        self.H, self.Z, self.theta = H, Z, theta
        z0, z1 = self.z[:-1], self.z[1:]
        self.h = z1 - z0
        self.za = z0 + _G1 * self.h
        self.zb = z0 + _G2 * self.h
        self.s6a, self.s6b = s6(self.za, H), s6(self.zb, H)
        self.sin = sin6(self.z, H)
        self.m_nodes = None

    def set_mass(self, m_nodes, m_inf):
        self.m_nodes = np.asarray(m_nodes, float)
        self.m_inf = float(m_inf)
        ip = PchipInterpolator(self.z, self.m_nodes)
        self.ma, self.mb = ip(self.za), ip(self.zb)

    def _steps(self, Ks, ws):
        h = self.h[:, None]
        a1 = -self.s6a[:, None] * Ks[None, :]
        a2 = -self.s6b[:, None] * Ks[None, :]
        b1 = self.ma[:, None]
        b2 = self.mb[:, None]
        c1 = c2 = ws[None, :]
        sq = math.sqrt(3.0) / 12.0 * h * h
        al = -(0.5 * h * (a1 + a2) - 2.0 * sq * (b2 * c1 - c2 * b1))       # backward: exp(-Omega)
        be = -(0.5 * h * (b1 + b2) - 2.0 * sq * (c2 * a1 - a2 * c1))
        ga = -(0.5 * h * (c1 + c2) + 2.0 * sq * (a2 * b1 - b2 * a1))
        lam2 = al * al + be * be - ga * ga
        lam = np.sqrt(np.abs(lam2))
        small = lam < 1e-6
        with np.errstate(over="ignore", invalid="ignore", divide="ignore"):
            C = np.where(lam2 >= 0, np.cosh(lam), np.cos(lam))
            S = np.where(lam2 >= 0, np.sinh(lam), np.sin(lam)) / np.where(small, 1.0, lam)
        C = np.where(small, 1.0 + 0.5 * lam2, C)
        S = np.where(small, 1.0 + lam2 / 6.0, S)
        return C, S, al, be, ga

    def _start(self, Ks, ws):
        R = np.sqrt(self.m_inf ** 2 + Ks ** 2)
        alpha = np.arctan2(Ks, self.m_inf)
        pd = 0.5 * (alpha - np.arccos(np.clip(ws / R, -1.0, 1.0)))
        return pd, R

    def shoot(self, Ks, ws, store=False):
        """Backward from Z to 0.  Returns p(0) (continuous) and, if store, (p, ln r) at all nodes."""
        Ks = np.atleast_1d(np.asarray(Ks, float))
        ws = np.atleast_1d(np.asarray(ws, float))
        C, S, al, be, ga = self._steps(Ks, ws)
        pd, R = self._start(Ks, ws)
        f, g = np.cos(pd), np.sin(pd)
        p = pd.copy()
        lnr = np.zeros_like(p)
        n = C.shape[0]
        if store:
            P = np.empty((n + 1, p.size)); L = np.empty((n + 1, p.size))
            P[n], L[n] = p, lnr
        for i in range(n - 1, -1, -1):
            Ci, Si, a, b, c = C[i], S[i], al[i], be[i], ga[i]
            fn = (Ci + Si * a) * f + Si * (b + c) * g
            gn = Si * (b - c) * f + (Ci - Si * a) * g
            p = p + np.arctan2(f * gn - g * fn, f * fn + g * gn)
            nr = np.hypot(fn, gn)
            f, g = fn / nr, gn / nr
            lnr = lnr + np.log(nr)
            if store:
                P[i], L[i] = p, lnr
        if store:
            return p, P, L
        return p

    def delta(self, Ks, ws):
        return (self.theta + math.pi / 2) - self.shoot(Ks, ws)

    def orbitals(self, Ks, ws):
        """Normalized (f, g) on the nodes (columns = batch), Int_0^inf (f^2+g^2) dz = 1 incl. the exact tail."""
        p0, P, L = self.shoot(Ks, ws, store=True)
        Lmax = L.max(axis=0)
        r = np.exp(L - Lmax[None, :])
        f, g = r * np.cos(P), r * np.sin(P)
        R = np.sqrt(self.m_inf ** 2 + np.asarray(Ks, float) ** 2)
        kap = np.sqrt(np.maximum(R ** 2 - np.asarray(ws, float) ** 2, 1e-300))
        tail = (f[-1] ** 2 + g[-1] ** 2) / (2 * kap)
        norm2 = simpson(f * f + g * g, x=self.z, axis=0) + tail
        c = 1.0 / np.sqrt(norm2)
        self.last_tail = tail / norm2               # fraction of each orbital beyond Z (exact exponential tail)
        return f * c, g * c, kap

    # -- levels ------------------------------------------------------------------------------------
    def levels(self, ks, s, wmin=0.0):
        """All levels with wmin < w < R of the block ODE with K = s*k, for every k in ks.
        Returns list of (k_index, j, w, kappa)."""
        ks = np.asarray(ks, float)
        Ks = s * ks
        R = np.sqrt(self.m_inf ** 2 + ks ** 2)
        DR = self.delta(Ks, R)
        D0 = self.delta(Ks, np.full_like(ks, wmin))
        items = []
        for i in range(ks.size):
            for j in range(math.floor(DR[i] / math.pi) + 1, math.ceil(D0[i] / math.pi)):
                items.append((i, j))
        if not items:
            return []
        idx = np.array([it[0] for it in items]); jj = np.array([it[1] for it in items], float)
        w = self.solve_levels(Ks[idx], R[idx], jj, wmin)
        kap = np.sqrt(np.maximum(R[idx] ** 2 - w ** 2, 0.0))
        return [(int(idx[q]), int(jj[q]), float(w[q]), float(kap[q])) for q in range(len(items))]

    def solve_levels(self, Ks, R, jj, wmin=0.0, iters=56):
        """Vectorized bisection in log(kappa) on Delta(w(kappa)) = j pi, w = +sqrt(R^2 - kappa^2) in (wmin, R)."""
        kmax = np.sqrt(np.maximum(R ** 2 - wmin ** 2, 0.0))
        lo = np.log(1e-13 * R)
        hi = np.log(np.maximum(kmax, 1e-300))
        for _ in range(iters):
            mid = 0.5 * (lo + hi)
            w = np.sqrt(np.maximum(R ** 2 - np.exp(2 * mid), 0.0))
            fm = self.delta(Ks, w) - jj * math.pi        # increasing in kappa
            hi = np.where(fm > 0, mid, hi)
            lo = np.where(fm > 0, lo, mid)
        k = np.exp(0.5 * (lo + hi))
        return np.sqrt(np.maximum(R ** 2 - k * k, 0.0))

    def band_edge(self, s, j, k_in, k_out, kind="threshold", iters=48):
        """k where band (s, j) stops existing between k_in (exists) and k_out (does not):
        kind='threshold': Delta(R(k), k) = j pi (merges into the continuum);  'zero': Delta(0, k) = j pi."""
        a, b = np.asarray(k_in, float).copy(), np.asarray(k_out, float).copy()
        j = np.asarray(j, float)
        for _ in range(iters):
            mid = 0.5 * (a + b)
            R = np.sqrt(self.m_inf ** 2 + mid ** 2)
            w = R if kind == "threshold" else np.zeros_like(mid)
            D = self.delta(s * mid, w)
            exists = (D < j * math.pi) if kind == "threshold" else (D > j * math.pi)
            a = np.where(exists, mid, a)
            b = np.where(exists, b, mid)
        return 0.5 * (a + b)


@dataclass
class Band:
    s: int                    # +1: irrep w3 = -i ; -1: irrep w3 = +i
    j: int                    # Pruefer index of the level
    k: np.ndarray             # k-grid points where it exists (plus the edge)
    w: np.ndarray             # omega on those points
    k_lo: float               # lower end of existence (threshold, zero crossing or 0)
    k_hi: float               # upper end (inf if it exists up to the grid end)
    label: str = ""

    def interp(self):
        return PchipInterpolator(self.k, self.w, extrapolate=True)

    def kF(self, mu):
        """Fermi momentum for Fermi level mu (band assumed increasing in k)."""
        if mu <= self.w[0]:
            return self.k_lo
        if mu >= self.w[-1]:
            if self.k_hi < np.inf:
                return self.k_hi
            # extrapolate linearly with the last slope
            sl = (self.w[-1] - self.w[-2]) / (self.k[-1] - self.k[-2])
            return self.k[-1] + (mu - self.w[-1]) / sl
        ip = self.interp()
        return brentq(lambda k: float(ip(k)) - mu, self.k[0], self.k[-1], xtol=1e-13)


def build_bands(ks_grid: KSGrid, kgrid, m0):
    """Band structure omega_b(k) (positive levels, both irreps) on kgrid, with band edges refined."""
    kgrid = np.asarray(kgrid, float)
    bands = []
    for s in (+1, -1):
        lv = ks_grid.levels(kgrid, s)
        js = sorted(set(j for (_, j, _, _) in lv))
        for j in js:
            pts = sorted([(kgrid[i], w) for (i, jj, w, _) in lv if jj == j])
            kk = np.array([p[0] for p in pts]); ww = np.array([p[1] for p in pts])
            present = np.isin(kgrid, kk)
            first = np.argmax(present)
            k_lo, k_hi = 0.0, np.inf
            if first > 0:
                # lower edge: threshold (merges with continuum) or zero crossing
                kin, kout = kgrid[first], kgrid[first - 1]
                Rin = math.hypot(m0, kin)
                kind = "threshold" if (Rin - ww[0]) < ww[0] else "zero"
                k_lo = float(ks_grid.band_edge(s, np.array([j]), np.array([kin]), np.array([kout]), kind)[0])
                w_lo = math.hypot(m0, k_lo) if kind == "threshold" else 0.0
                kk = np.concatenate(([k_lo], kk)); ww = np.concatenate(([w_lo], ww))
            last = len(kgrid) - 1 - np.argmax(present[::-1])
            if last < len(kgrid) - 1 and not present[last + 1:].any():
                kin, kout = kgrid[last], kgrid[last + 1]
                Rin = math.hypot(m0, kin)
                kind = "threshold" if abs(Rin - ww[-1]) < abs(ww[-1]) else "zero"
                k_hi = float(ks_grid.band_edge(s, np.array([j]), np.array([kin]), np.array([kout]), kind)[0])
                w_hi = math.hypot(m0, k_hi) if kind == "threshold" else 0.0
                kk = np.concatenate((kk, [k_hi])); ww = np.concatenate((ww, [w_hi]))
            if not np.all(np.diff(ww) > -1e-12):
                print(f"   [warn] band s={s} j={j} is not monotone in k on the grid")
            bands.append(Band(s=s, j=j, k=kk, w=ww, k_lo=k_lo, k_hi=k_hi))
    # label bands by their bottom energy: n = 0, 1, 2, ...
    bands.sort(key=lambda b: b.w[0])
    for n, b in enumerate(bands):
        b.label = f"n={n} ({'-i' if b.s > 0 else '+i'}, j={b.j})"
    return bands


def _dos(kF, klo):
    return 4.0 / (6.0 * math.pi ** 2) * max(kF ** 3 - klo ** 3, 0.0)


@dataclass
class KSResult:
    converged: bool
    iterations: int
    mu: float | None
    E_per_A: float
    sum_omega: float
    E_int: float
    occupations: list
    z: np.ndarray
    sigma: np.ndarray
    m: np.ndarray
    n: np.ndarray
    history: list
    bands: list
    notes: list = field(default_factory=list)


def ks_solve(Ns, m0=1.0, lam=-0.01, eps=+1, H=1.0, fractions=None, kgrid=None, Z=30.0, h_near=0.003,
             n_gl=16, mix=0.5, tol=1e-8, maxit=80, m_init=None, verbose=True, band_select=None, anderson=5):
    """Kohn-Sham self-consistency at surface density Ns (per unit coordinate observed 3-volume, V_hid = 1).

    fractions: None -> common Fermi level (ground state within the wall-bound sector);
               dict {band_index_n: fraction} -> Delta-SCF with fixed band occupations N_n = fraction * Ns,
               each band filled from its bottom (the lowest-energy configuration with those occupations).
    """
    th = theta_MIT(eps)
    G = KSGrid(Z=Z, h_near=h_near, H=H, theta=th)
    if m_init is None:
        m_nodes = np.full(G.z.size, m0)
    elif callable(m_init):
        m_nodes = np.asarray(m_init(G.z), float)
    else:
        m_nodes = np.asarray(m_init, float)
    G.set_mass(m_nodes, m0)
    kgrid = np.linspace(0.0, 20.0, 41) if kgrid is None else np.asarray(kgrid, float)
    xg, wg_ = np.polynomial.legendre.leggauss(n_gl)
    hist = []
    notes = []
    converged = False
    sig = np.zeros_like(G.z)
    Xh, Rh = [], []
    for it in range(1, maxit + 1):
        t0 = time.time()
        bands = build_bands(G, kgrid, m0)
        if band_select is not None:
            bands = [b for b in bands if band_select(b)]
        if not bands:
            notes.append(f"iteration {it}: no bound positive band on the k-grid [0, {kgrid[-1]}]")
            return KSResult(False, it, None, float("nan"), float("nan"), float("nan"), [], G.z, sig, G.m_nodes,
                            np.zeros_like(G.z), hist, [], notes)
        # occupations
        if fractions is None:
            Nfun = lambda mu: sum(_dos(b.kF(mu), b.k_lo) for b in bands) - Ns
            mu_lo = min(b.w[0] for b in bands) + 1e-12
            mu_hi = mu_lo + 1.0
            while Nfun(mu_hi) < 0:
                mu_hi = mu_lo + 2 * (mu_hi - mu_lo)
                if mu_hi > 1e6:
                    raise RuntimeError("cannot bracket the Fermi level")
            mu = brentq(Nfun, mu_lo, mu_hi, xtol=1e-13)
            occ = [(b, b.k_lo, b.kF(mu)) for b in bands if b.kF(mu) > b.k_lo]
        else:
            mu = None
            occ = []
            for n_idx, frac in fractions.items():
                b = bands[n_idx]
                Nb = frac * Ns
                kF = (Nb * 6 * math.pi ** 2 / 4.0 + b.k_lo ** 3) ** (1.0 / 3.0)
                if b.k_hi < np.inf and kF > b.k_hi:
                    raise RuntimeError(f"band {b.label} cannot hold {Nb}")
                occ.append((b, b.k_lo, kF))
        # orbitals at Gauss-Legendre nodes of every occupied interval
        sig_new = np.zeros_like(G.z)
        nden = np.zeros_like(G.z)
        sum_w = 0.0
        N_tail = 0.0
        occ_info = []
        for (b, klo, kF) in occ:
            kn = 0.5 * (kF - klo) * xg + 0.5 * (kF + klo)
            wn = 0.5 * (kF - klo) * wg_
            R = np.sqrt(m0 ** 2 + kn ** 2)
            wlev = G.solve_levels(b.s * kn, R, np.full(kn.size, float(b.j)))
            f, g, kap = G.orbitals(b.s * kn, wlev)
            wt = 4.0 / (2.0 * math.pi ** 2) * wn * kn ** 2          # 4 Int d^3k/(2pi)^3 -> 4/(2 pi^2) k^2 dk
            sig_new += G.sin * ((f * f - g * g) @ wt)
            nden += G.sin * ((f * f + g * g) @ wt)
            sum_w += float(np.sum(wt * wlev))
            N_tail += float(np.sum(wt * G.last_tail))
            occ_info.append(dict(band=b.label, s=b.s, j=b.j, k_lo=klo, kF=kF, N=float(np.sum(wt)),
                                 w_bottom=float(b.w[0]), w_top=float(wlev.max()) if kF > klo else float("nan")))
        m_new = m0 + lam * sig_new
        res = float(np.max(np.abs(m_new - G.m_nodes)))
        with np.errstate(divide="ignore", invalid="ignore"):
            integrand = np.where(G.sin > 0, sig_new ** 2 / G.sin, 0.0)
            nper = np.where(G.sin > 0, nden / G.sin, 0.0)
        E_int = -0.5 * lam * float(simpson(integrand, x=G.z))       # Int (W - sigma W') dV, W - sigma W' = -(lam/2) sigma^2
        E = sum_w + E_int
        Ncheck = float(simpson(nper, x=G.z)) + N_tail
        zc = float(simpson(G.z * nper, x=G.z)) / max(float(simpson(nper, x=G.z)), 1e-300)   # centre of the layer
        hist.append(dict(it=it, residual=res, E=E, mu=mu, N=Ncheck, zc=zc, seconds=time.time() - t0))
        if verbose:
            occs = ", ".join(f"{o['band']}: kF={o['kF']:.5f} N={o['N']:.5g}" for o in occ_info)
            print(f"   it {it:3d}  max|m_new - m| = {res:.3e}  E/A = {E:.10f}  mu = {mu if mu is None else round(mu, 10)}"
                  f"  N(check) = {Ncheck:.8f}  z_c = {zc:.5f}  [{occs}]  ({time.time() - t0:.1f}s)", flush=True)
        sig = sig_new
        if res < tol:
            converged = True
            G.set_mass(m_new, m0)
            break
        # Anderson (Pulay) mixing on m(z); plain linear mixing for the first step
        x, r = G.m_nodes.copy(), m_new - G.m_nodes
        Xh.append(x); Rh.append(r)
        Xh[:] = Xh[-(anderson + 1):]; Rh[:] = Rh[-(anderson + 1):]
        if anderson and len(Xh) >= 2:
            dX = np.array([Xh[i + 1] - Xh[i] for i in range(len(Xh) - 1)]).T
            dR = np.array([Rh[i + 1] - Rh[i] for i in range(len(Rh) - 1)]).T
            gam = np.linalg.lstsq(dR, r, rcond=None)[0]
            x_new = x + mix * r - (dX + mix * dR) @ gam
        else:
            x_new = x + mix * r
        G.set_mass(x_new, m0)
    return KSResult(converged, it, mu, E, sum_w, E_int, occ_info, G.z, sig, G.m_nodes, nden, hist, bands, notes)


def walecka_check(res: KSResult, m0, lam, eps, Ns, kgrid, Z=30.0, h_near=0.003, n_gl=16, delta=0.02):
    """Variational check of a converged ground state: the Walecka functional
        Omega[m] = sum_occ omega[m] + Int (m - m0)^2 / (2|lam|) dz/Sin
    equals E at the self-consistent m and is larger for m +- delta * (m_sc - m0) (lam < 0)."""
    out = []
    for scale in (1.0 - delta, 1.0, 1.0 + delta):
        mtrial = m0 + scale * (res.m - m0)
        G = KSGrid(Z=Z, h_near=h_near, theta=theta_MIT(eps))
        G.set_mass(mtrial, m0)
        bands = build_bands(G, kgrid, m0)
        Nfun = lambda mu: sum(_dos(b.kF(mu), b.k_lo) for b in bands) - Ns
        mu_lo = min(b.w[0] for b in bands) + 1e-12
        mu = brentq(Nfun, mu_lo, mu_lo + 1e3, xtol=1e-13)
        xg, wg_ = np.polynomial.legendre.leggauss(n_gl)
        sw = 0.0
        for b in bands:
            kF = b.kF(mu)
            if kF <= b.k_lo:
                continue
            kn = 0.5 * (kF - b.k_lo) * xg + 0.5 * (kF + b.k_lo)
            wn = 0.5 * (kF - b.k_lo) * wg_
            wl = G.solve_levels(b.s * kn, np.sqrt(m0 ** 2 + kn ** 2), np.full(kn.size, float(b.j)))
            sw += float(np.sum(4.0 / (2 * math.pi ** 2) * wn * kn ** 2 * wl))
        with np.errstate(divide="ignore", invalid="ignore"):
            integ = np.where(G.sin > 0, (mtrial - m0) ** 2 / G.sin, 0.0)
        Om = sw + float(simpson(integ, x=G.z)) / (2 * abs(lam))
        out.append((scale, Om, mu, [(b.label, b.k_lo, float(b.w[0])) for b in bands]))
    return out


